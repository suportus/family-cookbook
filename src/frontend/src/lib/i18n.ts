export type Language = "en" | "sl";
export type TranslationKey = keyof typeof translations.en;

// Helper function to format dates
export function formatDate(timestamp: bigint, language: Language): string {
  const date = new Date(Number(timestamp / BigInt(1000000)));
  return date.toLocaleDateString(language === "sl" ? "sl-SI" : "en-US", {
    year: "numeric",
    month: "long",
    day: "numeric",
  });
}

// Helper function to format dates in short format
export function formatDateShort(timestamp: bigint, language: Language): string {
  const date = new Date(Number(timestamp / BigInt(1000000)));
  return date.toLocaleDateString(language === "sl" ? "sl-SI" : "en-US", {
    year: "numeric",
    month: "short",
    day: "numeric",
  });
}
